//  Pairing-code redemption. A crew member generates a short code on Crew Deck
//  (the crew website — issuing the code IS the consent); the family redeems it
//  here.
//
//  The code carries the crew member's identity server-side — the family never
//  types an ID of any kind, and a guessed/mistyped code simply won't redeem.
//  There is no backend yet, so `MockPairingService` resolves a small set of
//  seeded codes locally. `RemotePairingService` is the real implementation,
//  ready to point at the API once it's hosted. Swap via `Pairing.service`.
